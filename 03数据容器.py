# ---------集合set---------
# --集合是一种无序、可变，可以存储任意类型的元素，但不允许重复元素
# --集合的定义：使用花括号{}，元素之间用逗号分隔，或者使用set()函数创建空集合
# --集合的访问：由于集合是无序的，所以不能通过索引访问元素，但可以使用for循环遍历集合中的元素
# --集合的修改：使用add(e)方法添加元素，使用remove(e)方法删除元素，使用update()方法更新集合，使用discard()方法删除指定元素，使用pop()方法随机删除一个元素，使用clear()方法清空集合
# --集合的其他操作：使用len()函数获取集合长度，使用in运算符判断元素是否在集合中，使用union()方法 或 |运算符 求并集，使用intersection()方法 或 &运算符 求交集，使用difference()方法 或 -运算符 求差集
# 注意：{}表示空字典，而不是空集合，空集合需要使用set()函数创建
